import fs from "node:fs"
import { getJyutpingList } from "to-jyutping"

const cache = new URL("../.cache/", import.meta.url)
const essay = fs.readFileSync(new URL("essay-cantonese.txt", cache), "utf8")
const wordsYaml = fs.readFileSync(new URL("jyut6ping3.words.dict.yaml", cache), "utf8")
const mandoText = fs.readFileSync(new URL("canto_mando_words.txt", cache), "utf8")
const stText = fs.readFileSync(new URL("TSCharacters.txt", cache), "utf8")

const syllable = /^[a-z]+[1-6]$/
const han = /^[\u3400-\u9fff]+$/

const simplified = new Map()
for (const line of stText.split(/\n/)) {
  if (!line || line.startsWith("#")) continue
  const [from, to] = line.split("\t")
  if (from && to) simplified.set(from, to.split(" ")[0])
}

function toSimplified(text) {
  return Array.from(text)
    .map((char) => simplified.get(char) ?? char)
    .join("")
}

const lexicon = new Set()
for (const line of wordsYaml.split(/\n/)) {
  if (!line || line.startsWith("#") || line.startsWith("-")) continue
  const tab = line.indexOf("\t")
  if (tab <= 0) continue
  const text = line.slice(0, tab).trim()
  if (han.test(text) && text.length >= 2 && text.length <= 4) lexicon.add(text)
}

const glossOf = new Map()
for (const line of mandoText.split(/\n/)) {
  const tab = line.indexOf("\t")
  if (tab <= 0) continue
  const gloss = toSimplified(line.slice(tab + 1).split(/[，,、]/)[0].trim())
  if (!gloss) continue
  for (const alt of line.slice(0, tab).split(/[,，]/)) {
    const text = alt.trim()
    if (text && !glossOf.has(text)) glossOf.set(text, gloss)
  }
}

const ranked = []
for (const line of essay.split(/\n/)) {
  const tab = line.lastIndexOf("\t")
  if (tab <= 0) continue
  const text = line.slice(0, tab).trim()
  const count = Number(line.slice(tab + 1))
  if (!Number.isFinite(count) || count <= 0) continue
  if (!lexicon.has(text)) continue
  if (/^(.)\1+$/.test(text)) continue
  ranked.push([count, text])
}
ranked.sort((a, b) => b[0] - a[0] || a[1].localeCompare(b[1], "zh"))

const rows = []
let rejected = 0
const seen = new Set()
for (const [, text] of ranked) {
  if (rows.length >= 3000) break
  if (seen.has(text)) continue
  seen.add(text)
  const parts = getJyutpingList(text)
  const chars = Array.from(text)
  const ok =
    parts.length === chars.length &&
    parts.every(([char, reading], index) => {
      if (char !== chars[index] || !reading) return false
      const syllables = reading.split(/\s+/).filter(Boolean)
      return syllables.length === 1 && syllable.test(syllables[0])
    })
  if (!ok) {
    rejected += 1
    continue
  }
  const gloss = (glossOf.get(text) ?? toSimplified(text)).slice(0, 16)
  rows.push([text, gloss])
}

const fromDict = rows.filter(([text, gloss]) => glossOf.get(text) === gloss || glossOf.has(text)).length
console.log(
  JSON.stringify(
    {
      lexicon: lexicon.size,
      ranked: ranked.length,
      kept: rows.length,
      rejected,
      glossFromDictionary: fromDict,
      glossFromWriting: rows.length - fromDict,
      head: rows.slice(0, 24),
      tail: rows.slice(-8),
    },
    null,
    2,
  ),
)

const lessons = []
for (let index = 0; index < rows.length; index += 20) {
  const slice = rows.slice(index, index + 20)
  const start = index + 1
  const end = index + slice.length
  lessons.push({ start, end, slice })
}

const list = rows.map(([text, gloss]) => `  [${JSON.stringify(text)}, ${JSON.stringify(gloss)}],`).join("\n")
const source = `// Generated by scripts/build-common-words.mjs. Do not edit by hand.
// Order follows the word counts in rime-cantonese essay-cantonese.txt.
// That file is part of Rime Cantonese, CC BY 4.0, © CanCLID.
// A meaning is the Mandarin gloss from 开放词典 when the word is listed there, CC BY 3.0, © 开放词典.
// Otherwise the gloss is the same word in simplified characters, via OpenCC (Apache-2.0).
// Jyutping is not stored in this file. The app looks each word up with to-jyutping.

import { word } from "../lib/reading"
import type { Lesson } from "../lib/types"

const rows: Array<[string, string]> = [
${list}
]

export const commonLessons: Lesson[] = []

for (let index = 0; index < rows.length; index += 20) {
  const slice = rows.slice(index, index + 20)
  const start = index + 1
  const end = index + slice.length
  const id = "common-" + String(start).padStart(4, "0")
  commonLessons.push({
    id,
    title: start + "–" + end,
    blurb: slice
      .slice(0, 4)
      .map(([, gloss]) => gloss)
      .join("、"),
    sentences: slice.map(([text, gloss], offset) => ({
      id: id + "-" + String(offset + 1).padStart(2, "0"),
      gloss,
      tokens: [word(text, gloss)],
    })),
  })
}
`

fs.writeFileSync(new URL("../src/data/common-words.ts", import.meta.url), source)
console.log("lessons", lessons.length)
