// Words are a regrouping of the 3000-word list, not a second word list.
import { word } from "../lib/reading"
import type { Lesson } from "../lib/types"

function lesson(id: string, title: string, blurb: string, rows: Array<[string, string]>): Lesson {
  return {
    id,
    title,
    blurb,
    sentences: rows.map(([text, gloss], index) => ({
      id: id + "-" + String(index + 1).padStart(2, "0"),
      gloss,
      tokens: [word(text, gloss)],
    })),
  }
}

